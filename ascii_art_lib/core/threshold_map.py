"""Матрицы порога (threshold maps) и вспомогательные матричные фильтры."""

from __future__ import annotations

import numpy as np


class ThresholdMap:
    """Набор матриц Байера/упорядоченного дизеринга разных размеров."""

    Mat_2 = np.array(
        [[0.0, 0.5],
         [0.75, 1.0]]
    )

    Mat_4 = np.array(
        [[0.0, 0.5, 0.125, 0.625],
         [0.75, 1.0, 0.875, 1.125],
         [0.1875, 0.6875, 0.25, 0.75],
         [0.9375, 1.1875, 1.0, 1.25]]
    )

    Mat_8 = np.array(
        [[0.0, 0.5, 0.125, 0.625, 0.03125, 0.53125, 0.15625, 0.65625],
         [0.75, 1.0, 0.875, 1.125, 0.78125, 1.03125, 0.90625, 1.15625],
         [0.1875, 0.6875, 0.25, 0.75, 0.21875, 0.71875, 0.28125, 0.78125],
         [0.9375, 1.1875, 1.0, 1.25, 0.96875, 1.21875, 1.03125, 1.28125],
         [0.046875, 0.546875, 0.171875, 0.671875, 0.0625, 0.5625, 0.1875, 0.6875],
         [0.796875, 1.046875, 0.921875, 1.171875, 0.8125, 1.0625, 0.9375, 1.1875],
         [0.234375, 0.734375, 0.296875, 0.796875, 0.25, 0.75, 0.3125, 0.8125],
         [0.984375, 1.234375, 1.046875, 1.296875, 1.0, 1.25, 1.0625, 1.3125]]
    )

    @staticmethod
    def Mat2N(n: int) -> np.ndarray:
        """Рекурсивно строит матрицу дизеринга размера ``n x n`` (n — степень двойки)."""
        assert n % 2 == 0 and isinstance(n, int), "n должен быть чётным целым"
        if n > 2:
            return (
                np.kron(np.ones((2, 2)), ThresholdMap.Mat2N(n // 2))
                + np.kron(ThresholdMap.Mat_2, np.ones((n // 2, n // 2))) / ((n / 2) ** 2)
            )
        return ThresholdMap.Mat_2


